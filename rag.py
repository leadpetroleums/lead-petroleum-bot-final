@dataclass
class Citation:
    product_name: str
    page_ref: int


@dataclass
class Answer:
    text: str
    intent: Intent
    citations: list[Citation] = field(default_factory=list)
    confidence: float = 1.0
    products_used: list[dict] = field(default_factory=list)


